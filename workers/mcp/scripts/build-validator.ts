// Precompile the ViewPlan JSON Schema into a standalone ajv validator.
// workerd blocks runtime code generation (eval / new Function), so ajv cannot compile at request time.
//
//   node scripts/build-validator.ts          write src/generated/view-plan-validator.js
//   node scripts/build-validator.ts --check  fail if the committed file is stale (run by `pnpm test`)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import _Ajv2020 from "ajv/dist/2020.js";
import _standalone from "ajv/dist/standalone/index.js";

type Mod<T> = T | { default: T };
const unwrap = <T>(m: Mod<T>): T =>
  "default" in (m as object) ? (m as { default: T }).default : (m as T);
const Ajv2020 = unwrap(_Ajv2020 as unknown as Mod<typeof _Ajv2020.default>);
const standalone = unwrap(_standalone as unknown as Mod<typeof _standalone.default>);

const schemaPath = fileURLToPath(
  new URL("../../../packages/contracts/schemas/view-plan.schema.json", import.meta.url),
);
const outPath = fileURLToPath(new URL("../src/generated/view-plan-validator.js", import.meta.url));

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
const body = standalone(ajv, validate);
// The catalog is whatever the schema's oneOf lists, so the two can never drift.
const types: string[] = schema.properties.components.items.oneOf.map(
  (r: { $ref: string }) => r.$ref.split("/").pop() as string,
);
const catalog = `\nexport const COMPONENT_TYPES = ${JSON.stringify(types)};\n`;

const banner = `// biome-ignore-all lint: generated file
// biome-ignore-all format: generated file
// GENERATED by workers/mcp/scripts/build-validator.ts from packages/contracts/schemas/view-plan.schema.json.
// Do not edit. Regenerate with: pnpm --filter @secondary/mcp gen:validator
`;
const next = `${banner}${body}${catalog}`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {}
  if (current !== next) {
    console.error(
      "view-plan-validator.js is stale. Run: pnpm --filter @secondary/mcp gen:validator",
    );
    process.exit(1);
  }
  console.log("view-plan-validator.js is up to date");
} else {
  writeFileSync(outPath, next);
  console.log(`wrote ${outPath} (${next.length} bytes)`);
}

// Precompile the ViewPlan JSON Schema into a standalone ajv validator.
// workerd blocks runtime code generation (new Function), so the validator is generated at build time.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../../../packages/contracts/schemas/view-plan.schema.json");
const out = resolve(here, "../src/generated/view-plan.validator.js");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
// Standalone output still `require`s two tiny ajv runtime helpers. Inline them so the module is plain ESM.
const HELPERS = `
const __ucs2length = (str) => {
  let length = 0;
  for (let pos = 0; pos < str.length; ) {
    length++;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < str.length && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos++;
  }
  return length;
};
const __equal = (a, b) => {
  if (a === b) return true;
  if (!a || !b || typeof a !== "object" || typeof b !== "object") return false;
  if (Array.isArray(a)) return Array.isArray(b) && a.length === b.length && a.every((x, i) => __equal(x, b[i]));
  if (Array.isArray(b)) return false;
  const ka = Object.keys(a);
  return ka.length === Object.keys(b).length && ka.every((k) => Object.hasOwn(b, k) && __equal(a[k], b[k]));
};
`;
const code = standaloneCode(ajv, validate)
  .replace('require("ajv/dist/runtime/ucs2length").default', "__ucs2length")
  .replace('require("ajv/dist/runtime/equal").default', "__equal");
if (code.includes("require(")) throw new Error("standalone validator still uses require()");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// @generated by scripts/gen-validator.mjs from view-plan.schema.json. Do not edit.\n${HELPERS}${code}`,
);
writeFileSync(
  out.replace(/\.js$/, ".d.ts"),
  "// @generated\nexport declare const validate: (data: unknown) => boolean;\nexport default validate;\n",
);
console.log(`wrote ${out}`);
